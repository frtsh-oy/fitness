// Дорисовка человечка поверх схемы чужой библиотеки.
//
// Библиотека рисует только то, что у неё размечено как мышца, поэтому у её
// фигуры нет ни стоп, ни кистей, а голова со спины заметно ниже, чем спереди.
// Замерено по её же полигонам (vendor/body-highlighter.esm.js): спереди нога
// обрывается на y=195.51, сзади уходит острым мыском до y=220, предплечья на
// обоих видах доходят ровно до x=0 и x=100, голова спереди 19.18 × 25.31, а
// сзади 19.15 × 20.00.
//
// Файл библиотеки не правим: недостающее рисуем своими фигурами поверх её
// схемы — тем же серым, которым она заливает незатронутую мышцу. Координаты
// ниже сняты с её полигонов, поэтому правка файла их обесценит; чтобы такая
// правка не прошла молча, файл привязан контрольной суммой SHA-256 в
// test/vendor.test.js — любое изменение его содержимого роняет тест.
import { ModelType } from './vendor/body-highlighter.esm.js';

const SVG_NS = 'http://www.w3.org/2000/svg';

// Бокс отрисовки вместо библиотечного `0 0 100 200`. Сама библиотека своими же
// полигонами из него вылезала: заднюю голень она рисует до y=220, то есть
// двадцать единиц голени в картинку не попадали вообще. Плюс место под
// дорисованное: кисти уходят до x=-5.3 и x=105.3 (запястье у библиотеки на
// самом краю бокса), задние стопы — до y=230.5. Отсюда -8 и 116 по ширине
// (2.7 единицы запаса с каждой стороны) и 232 по высоте (1.5 под стопой).
// Соотношение сторон осталось 1:2, как у библиотеки, — высота схемы на
// странице от подъёма бокса не меняется.
export const VIEW_BOX = '-8 0 116 232';

// Передний вид у библиотеки короче заднего: её передняя модель кончается на
// y=195.51, задняя на y=220, то есть разница 24.49, а с дорисованными стопами
// 21.7 (208.8 против 230.5). Без сдвига на двух схемах рядом стояли бы люди
// разного роста, причём передний висел бы в воздухе. Сдвиг на 11 ставит
// середины обеих фигур в одну точку бокса с точностью до 0.15 единицы:
// (11+219.8)/2 = 115.4 у переднего против 230.5/2 = 115.25 у заднего.
const SHIFT = {
  [ModelType.ANTERIOR]: 11,
  [ModelType.POSTERIOR]: 0,
};

const polygon = points => ({ tag: 'polygon', attrs: { points } });

// Координаты — в единицах бокса библиотеки, сняты с её геометрии и согласованы
// макетом (борд «Предлагаю · карта тела»).
//
// Стопа переднего вида начинается на линии обрыва голени (y=195.5) и по ширине
// сходится с лодыжкой почти, но не совсем: слева библиотека кончает голень на
// x от 20.82 до 26.94 (стопа 20.8..26.9 — сходится), справа от 72.65 до 79.59
// против 72.7..79.2 у стопы, то есть с внешней стороны остаётся зарубка 0.39
// единицы ≈ 0.9px при отрисовке в 260px. Правки не просит: на телефоне не
// читается, а подгонять координаты макета под неё дороже, чем сказать о ней.
//
// Задняя стопа начинается выше обрыва (y=213) и накрывает острый мысок
// камбаловидной. Мысок при этом того же серого, что стопа (в наши 17 регионов
// камбаловидная не входит, значит цвет нагрузки ей не достаётся никогда), так
// что порядок наложения здесь ничего не меняет.
const EXTRAS = {
  [ModelType.ANTERIOR]: [
    polygon('20.8,195.5 26.9,195.5 28.4,202.5 26.8,208.8 19.4,208.8 17.8,202.5'),
    polygon('79.2,195.5 72.7,195.5 71.2,202.5 72.8,208.8 80.2,208.8 81.8,202.5'),
    // Кисти закрывают 1.35 ед² предплечий — 0.29% их площади, тонкий клин у
    // самого запястья. Под полигоны библиотеки их за этим не убираю: кисть
    // рисуется там, где у библиотеки ничего нет, а клин в треть процента
    // цвета нагрузки не прячет. Клики кистям не достаются вовсе — см.
    // pointer-events в decorate.
    polygon('0.4,98.9 6.6,102.1 5.0,107.5 0.3,113.5 -5.3,110.5 -3.5,103.5'),
    polygon('99.6,98.9 93.4,102.1 95.0,107.5 99.7,113.5 105.3,110.5 103.5,103.5'),
  ],
  [ModelType.POSTERIOR]: [
    polygon('27.5,213 33.5,213 34.5,222 33.0,230.5 27.8,230.5 26.3,222'),
    polygon('72.5,213 66.5,213 65.5,222 67.0,230.5 72.2,230.5 73.7,222'),
    polygon('0.4,106.4 6.6,109.6 5.0,115.0 0.3,121.0 -5.3,118.0 -3.5,111.0'),
    polygon('99.6,106.4 93.4,109.6 95.0,115.0 99.7,121.0 105.3,118.0 103.5,111.0'),
    // Голова со спины: эллипс вместо сплющенной. Ширина у него библиотечная
    // (40.4..59.6 против 40.43..59.57 у полигона), а высота — как у головы
    // спереди: 25.2 против 25.31.
    //
    // Лежит ПОД полигонами библиотеки (under), и это не стилистика. Эллипс
    // заходит на задние трапеции, и последним ребёнком он закрашивал 14.6 ед²
    // — 2.2% их площади, серый клин у основания шеи поверх цвета нагрузки, а
    // при выбранных трапециях поверх синего. Под ними он не закрывает ничего
    // (замерено растеризацией: 0.0 ед²), а высоту головы не теряет — видимый
    // низ серого остаётся на y=25.2 и в середине, и по максимуму, потому что
    // у трапеций посередине вырез под шею.
    //
    // Полигон головы рисуется теперь поверх эллипса, но он того же серого и
    // целиком внутри силуэта, поэтому видно ровно то же: 5 его вершин из 9
    // лежат снаружи эллипса (выносы по горизонтали 0.64, 0.57, 1.20, 2.11 и
    // 1.53 единицы, до ближайшего края эллипса максимум 1.83 ≈ 4.1px) — на
    // экране это слегка угловатые виски у овала.
    { tag: 'ellipse', attrs: { cx: '50', cy: '12.6', rx: '9.6', ry: '12.6' }, under: true },
  ],
};

// Приводит схему одного вида к нашему боксу: собирает всё нарисованное в одну
// группу со сдвигом и дорисовывает недостающее.
//
// Вызывать ОБЯЗАТЕЛЬНО после каждой отрисовки библиотеки, а не один раз при
// создании: её update() заменяет детей своего svg целиком (S(i, g) в
// vendor/body-highlighter.esm.js), то есть при каждой смене режима карты
// сносит и группу со сдвигом, и дорисованное. Ждёт свежеотрисованный svg —
// второй вызов подряд, без отрисовки между ними, вложил бы группу в группу и
// сдвинул фигуру дважды.
export function decorate(svg, { type, fill }) {
  const doc = svg.ownerDocument;
  const layer = doc.createElementNS(SVG_NS, 'g');
  layer.setAttribute('transform', `translate(0,${SHIFT[type]})`);

  const build = ({ tag, attrs }) => {
    const shape = doc.createElementNS(SVG_NS, tag);
    for (const [name, value] of Object.entries(attrs)) shape.setAttribute(name, value);
    // Цвет — через style.fill, как красит полигоны сама библиотека (h() в
    // vendor/body-highlighter.esm.js): так дорисованное и её незатронутая
    // мышца сравнимы одним и тем же свойством.
    shape.style.fill = fill;
    // Дорисованное — украшение, а не карта: клик по нему должен доставаться
    // мышце под ним. Своих слушателей у этих фигур нет, но кисти заходят на
    // предплечья, а эллипс головы — на трапеции, и без этого там появлялась
    // бы мёртвая зона без курсора-руки. В jsdom это не проверить: там клик
    // рассылается прямо по узлу и попадания никто не считает, — поэтому тест
    // сторожит сам атрибут.
    shape.setAttribute('pointer-events', 'none');
    return shape;
  };

  // Порядок детей — порядок наложения. Своё, помеченное under, идёт ПЕРЕД
  // полигонами библиотеки: там, где дорисованное заходит на цветную мышцу,
  // выигрывать обязан её цвет — он несёт число подходов, а наш серый нет.
  for (const shape of EXTRAS[type]) if (shape.under) layer.appendChild(build(shape));
  // Полигоны библиотеки переезжают в ту же группу: сдвиг обязан двигать фигуру
  // целиком. Сдвинуть отдельно дорисованное значило бы оторвать стопы от ног.
  while (svg.firstChild) layer.appendChild(svg.firstChild);
  for (const shape of EXTRAS[type]) if (!shape.under) layer.appendChild(build(shape));

  svg.appendChild(layer);
}
