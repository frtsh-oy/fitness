// Экран недельного объёма: собирает разметку по строкам из weekly-rows.js —
// расчёт, вердикт, подпись группы и сортировка уже соединены и посчитаны там,
// общим кодом с отчётом (tools/muscle-report.js). Своего расчёта и сортировки
// здесь нет.
import { weeklyRows } from './weekly-rows.js';

// Дробные значения бывают только у нашего числа: вспомогательная доля 0.5 на
// нечётном числе кругов даёт половину. Сопоставимое всегда целое.
function formatSets(sets) {
  return String(sets).replace('.', ',');
}

// className и text приходят непустыми при каждом вызове ниже — защит на
// пустую строку/undefined не заводим: в единственном месте, где text не
// передан (список-контейнер), `textContent = undefined` и так даёт "" на
// пустом узле, ничего не меняя.
function el(document, tag, className, text) {
  const node = document.createElement(tag);
  node.className = className;
  node.textContent = text;
  return node;
}

// Пометка «наша линия» — только когда ВСЯ граница полосы наша, без источника
// (basis ровно 'наша линия'; сегодня это только «выше изученного»). Раньше
// проверялось includes(), и пометка вдобавок ловила «рабочий объём» (basis:
// «низ из источника, верх — наша линия») — но вход в эту полосу подтверждён
// источником (Schoenfeld 2017: «десять и больше»), и та же пилюля с тем же
// текстом на «источник подтвердил» и на «мы придумали» стирала ровно ту
// разницу, которую обязана показывать (ревью task-3-review.md, находка 1: на
// настоящих данных пометка стояла на всех шести ненулевых строках и на всех
// шести врала). Частичный случай «рабочего объёма» — свойство ВСЕЙ полосы
// (граница 20, а не число 12 в ней), поэтому он не в пилюле построчно, а в
// тексте секции — см. WORKING_CEILING_NOTE ниже.
const OUR_LINE = 'наша линия';

function verdictCell(document, band) {
  const cell = el(document, 'span', 'weekly-verdict', band.verdict);
  if (band.basis === OUR_LINE) {
    cell.append(' ', el(document, 'span', 'weekly-basis', OUR_LINE));
  }
  return cell;
}

// Что значит пометка — до списка строк, а не после: на 375×812 от первой
// пилюли до оговорки после списка выходило 1472px (ревью, находка 5), то есть
// пометку видно, а что она значит — только проскроллив мимо всех двадцати
// строк. Текст не завязан на то, сколько строк пометку сейчас несут (их может
// быть и ноль — см. WORKING_CEILING_NOTE), поэтому не устареет, если данные
// изменятся.
const OUR_LINE_NOTE =
  'Пометка «наша линия» у вердикта означает: вся его граница — наше решение, а не источник.';

// Оговорка про «рабочий объём» — одна на секцию, а не в каждой из строк этой
// полосы: подтверждён источником у неё ВХОД (десять и больше), а не то число,
// что попало в полосу у конкретной группы, и это свойство границы 20, а не
// свойство строки с 12. Числа взяты из load-bands.js (max:20, why).
const WORKING_CEILING_NOTE =
  'У вердикта «рабочий объём» нижняя граница (десять подходов) подтверждена источником; верхнюю (двадцать) провели мы — общего потолка в проверенных источниках нет.';

// Второе (наряду с «количество, а не качество») ограничение из раздела спеки
// «Что калькулятор обязан говорить о себе» — туда, а не в описание решения,
// его и относит спека, значит место ему на экране, а не только в спеке.
// Ориентиры получены в основном на свободных весах; коэффициента, которым
// можно скорректировать числа под резинки, в источниках нет — оговорка
// остаётся оговоркой, а не поправкой.
const ECCENTRIC_LOAD_NOTE =
  'Резинки дают меньше эксцентрической нагрузки, чем свободные веса: при равном объёме рост сопоставим, но чуть уступает, а числа это не учитывают — коэффициента в источниках нет.';

export function renderWeekly({ host, workouts }) {
  const document = host.ownerDocument;
  host.textContent = '';

  const rows = weeklyRows(workouts);

  const list = el(document, 'div', 'weekly-list');
  for (const row of rows) {
    const line = el(document, 'div', 'weekly-row');
    line.append(
      el(document, 'span', 'weekly-name', row.label),
      el(document, 'span', 'weekly-main', formatSets(row.comparable)),
      el(document, 'span', 'weekly-ours', formatSets(row.ours)),
      verdictCell(document, row.band),
    );
    list.append(line);
  }

  host.append(
    el(document, 'p', 'weekly-head',
      'Подходов в неделю на группу мышц. Первое число — целевая работа, по нему и вердикт. Второе — как считает карта: вспомогательная работа идёт половиной.'),
    el(document, 'p', 'weekly-note', OUR_LINE_NOTE),
    list,
    el(document, 'p', 'weekly-note',
      'Калькулятор считает количество, а не качество: доводите вы подход до отказа или нет, из данных не видно.'),
    el(document, 'p', 'weekly-note', ECCENTRIC_LOAD_NOTE),
    el(document, 'p', 'weekly-note',
      'Односторонние упражнения в первом числе считаются по сторонам. Это наше чтение: договорённости об этом в проверенных источниках нет, в отличие от вспомогательной работы, для которой коэффициент половины назван прямо.'),
    el(document, 'p', 'weekly-note', WORKING_CEILING_NOTE),
  );
}
