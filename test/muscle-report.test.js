import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildReportLines } from '../tools/muscle-report.js';
import { MUSCLES, muscleLabel } from '../muscles.js';
import legsMwf from '../workouts/legs-mwf.js';

const VALID_LABELS = new Set(Object.values(MUSCLES).map(m => m.ru));

// Строки вида «| Ягодичные | 6 |» — ровно две колонки, число во второй.
// У таблицы «упражнение → мышцы» колонок шесть, под этот шаблон она не попадает.
function totalsRowLabels(text) {
  const labels = [];
  for (const line of text.split('\n')) {
    const m = /^\| ([^|]+) \| [\d.]+ \|$/.exec(line.trim());
    if (m) labels.push(m[1].trim());
  }
  return labels;
}

function untouchedLabels(text) {
  const m = /Не задействованы ни в одном упражнении: (.+)/.exec(text);
  assert.ok(m, 'в отчёте нет строки «Не задействованы»');
  return m[1] === '—' ? [] : m[1].split(', ');
}

// Строки одного раздела «### Заголовок» до следующего «### » или конца текста.
// Предполагает один WORKOUTS (сейчас так и есть — только legs-mwf): при второй
// зарегистрированной тренировке заголовок раздела повторится, и это придётся
// либо передавать сюда индекс вхождения, либо резать текст по workout.title.
function sectionRows(text, heading) {
  const after = text.split(`### ${heading}`)[1];
  assert.ok(after, `в отчёте нет раздела «${heading}»`);
  const section = after.split('\n### ')[0];
  const rows = [];
  for (const line of section.split('\n')) {
    const m = /^\| ([^|]+) \| ([\d.]+) \|$/.exec(line.trim());
    if (m) rows.push([m[1].trim(), Number(m[2])]);
  }
  return rows;
}

test('в сводку попадают все упражнения тренировки, без потерь и дублей', () => {
  const text = buildReportLines().join('\n');
  const names = legsMwf.blocks.flatMap(b => b.items).map(i => i.name);
  assert.equal(names.length, 19, 'в legs-mwf ожидается 19 упражнений — проверь фикстуру, если данные изменились');

  for (const name of names) {
    assert.ok(text.includes(name), `в отчёте нет упражнения «${name}»`);
  }
  // Строка таблицы «упражнение → мышцы» кончается меткой типа — по ней и считаем ряды,
  // отдельно от заголовков и от строк сводных таблиц подходов.
  const rows = text.split('\n').filter(line => /\| (Разминка|Силовое|Заминка) \|$/.test(line));
  assert.equal(rows.length, 19, 'число строк таблицы должно совпадать с числом упражнений');
});

test('подписи групп мышц в сводных таблицах подходов и в строке «Не задействованы» — из словаря MUSCLES', () => {
  // Название теста сузили умышленно: он смотрит только на сводные таблицы
  // подходов и строку «Не задействованы» — это отдельный код-путь (сложение
  // totalsByKind), а не на колонки «Целевые»/«Вспомогательные» основной
  // таблицы «упражнение → мышцы». Ту таблицу проверяет отдельный тест ниже —
  // «строки таблицы...» — и объединять их в один тест не стоит: они ловят
  // разные, не зависящие друг от друга поломки.
  const text = buildReportLines().join('\n');
  const labels = totalsRowLabels(text);
  assert.ok(labels.length > 0, 'сводные таблицы подходов пусты — тест ничего не проверяет');
  for (const label of labels) {
    assert.ok(VALID_LABELS.has(label), `«${label}» не найдена в словаре MUSCLES`);
  }
  for (const label of untouchedLabels(text)) {
    assert.ok(VALID_LABELS.has(label), `«${label}» из строки «Не задействованы» не найдена в словаре MUSCLES`);
  }
  // И конкретика, а не только «есть в словаре»: известный id даёт известную подпись.
  assert.ok(text.includes(muscleLabel('glutes')), 'нет подписи для glutes (Ягодичные)');
});

// РЕГРЕССИЯ (Critical из ревью): предыдущий раунд тестов проверял присутствие
// названий упражнений (тест выше) и подписи в СВОДНЫХ таблицах (тест выше) —
// но ни один тест не заглядывал в содержимое строк самой таблицы
// «упражнение → мышцы», то есть в то, ради чего этот документ существует.
// Из-за этого две независимые поломки проходили незамеченными:
//   1) перепутанные местами значения KIND_LABELS — колонка «Тип» лжёт для
//      каждой строки (силовое подписано «Разминка» и наоборот);
//   2) muscleLabel(id), подменённый на голый id в muscleColumns() — колонки
//      «Целевые»/«Вспомогательные» показывают английские идентификаторы
//      (hamstrings, glutes) вместо русских подписей.
// Ниже — по одной строке на каждый kind (Разминка/Силовое/Заминка), с разными
// формами колонок (несколько целевых, пустая вспомогательная, несколько
// вспомогательных, пустые обе). Строки скопированы дословно из проверенного
// глазами docs/muscle-map.md, а не набраны заново, чтобы не внести опечатку
// на стороне теста.
test('строки таблицы «упражнение → мышцы» содержат русские подписи мышц и верный тип, а не только название упражнения', () => {
  const text = buildReportLines().join('\n');
  const expectedRows = [
    // Разминка, несколько целевых групп + одна вспомогательная
    '| Разогрев | «Китайское» приседание с подъёмом таза и разворотом | Ноги и подвижность корпуса | Квадрицепсы, Ягодичные | Косые мышцы живота | Разминка |',
    // Силовое, одна целевая группа, вспомогательных нет (тире)
    '| Ноги 1 | Приведение ноги перед собой с резинкой | Внутренняя поверхность бедра | Приводящие | — | Силовое |',
    // Силовое, одна целевая, несколько вспомогательных
    '| Ноги 3 | «Птица-собака»: противоположные рука и нога | Корпус, ягодицы и плечевой пояс | Разгибатели поясницы | Ягодичные, Прямая мышца живота, Передняя дельта, Косые мышцы живота | Силовое |',
    // Заминка, целевых групп нет — тире в колонке «Целевые»
    '| Финиш | Спокойное дыхание | Восстановление дыхания | — | Прямая мышца живота | Заминка |',
  ];
  for (const row of expectedRows) {
    assert.ok(text.includes(row), `в отчёте нет точной строки:\n${row}`);
  }
});

test('«Не задействованы» согласована с load по ВСЕМ упражнениям тренировки (любого kind)', () => {
  const text = buildReportLines().join('\n');
  const untouched = new Set(untouchedLabels(text));
  const touchedIds = new Set(legsMwf.blocks.flatMap(b => b.items).flatMap(i => Object.keys(i.load)));

  for (const id of Object.keys(MUSCLES)) {
    const label = muscleLabel(id);
    if (touchedIds.has(id)) {
      assert.ok(!untouched.has(label), `«${label}» размечена хотя бы в одном упражнении, но названа незадействованной`);
    } else {
      assert.ok(untouched.has(label), `«${label}» нигде не размечена, но не упомянута как незадействованная`);
    }
  }
});

// Регрессия на конкретный дефект из ревью: старая версия генератора считала
// «Не задействованы» от totals одних силовых упражнений. Группа, занятая
// только в разминке, тогда попадала в этот список — прямая ложь для человека,
// который как раз и вычитывает разметку. Фикстура ниже не зависит от того,
// что сейчас размечено в legs-mwf.js, и ловит именно эту ошибку, если она
// вернётся.
function fixtureWorkouts() {
  return {
    fixture: {
      title: 'Фикстура для регрессии',
      blocks: [{
        nav: 'Блок',
        rounds: 3,
        items: [
          { name: 'Разминочное упражнение', muscles: 'Плечи', load: { traps: 0.5 }, kind: 'warmup' },
          { name: 'Силовое упражнение', muscles: 'Ягодицы', load: { glutes: 1 }, kind: 'strength' },
        ],
      }],
    },
  };
}

test('регрессия: группа, занятая только в разминке, не попадает в «Не задействованы»', () => {
  const text = buildReportLines(fixtureWorkouts()).join('\n');
  const untouched = new Set(untouchedLabels(text));

  assert.ok(!untouched.has(muscleLabel('traps')), 'трапеции размечены в разминке, но названы незадействованными');
  assert.ok(!untouched.has(muscleLabel('glutes')), 'ягодичные размечены в силовом, но названы незадействованными');
  assert.ok(untouched.has(muscleLabel('calves')), 'икроножные нигде не размечены и должны быть в списке');

  // И сама разминочная сводка не потеряла запись — иначе «не соврали» случайно,
  // выкинув строку целиком, а не потому что честно посчитали.
  assert.match(text, new RegExp(`${muscleLabel('traps')} \\| 1\\.5`));
});

// IMPORTANT из ревью: без сортировки по убыванию таблицы остаются формально
// верными (те же группы, те же числа), но перестают показывать самое важное —
// какая группа нагружена больше. Конкретно на этих данных: «Разгибатели
// поясницы» (3 подхода) — не самая очевидная мышца для высокого объёма в
// программе на ноги, и сортировка ставит её среди лидеров, а не прячет внизу
// вперемешку с порядком появления упражнений в файле. Тест ниже проверяет и
// общее свойство (не по возрастанию), и именно эту пару как читаемый якорь.
test('сводные таблицы подходов отсортированы по убыванию — иначе аномалии вроде «разгибатели поясницы выше квадрицепсов» останутся незамеченными', () => {
  const text = buildReportLines().join('\n');

  for (const heading of ['Силовые подходы за одну тренировку', 'Дополнительно нагружаются в разминке']) {
    const rows = sectionRows(text, heading);
    assert.ok(rows.length > 2, `«${heading}»: слишком мало строк, чтобы вообще проверить порядок`);
    for (let i = 1; i < rows.length; i++) {
      const [prevLabel, prevValue] = rows[i - 1];
      const [label, value] = rows[i];
      assert.ok(prevValue >= value, `«${heading}»: не по убыванию — ${prevLabel}=${prevValue} стоит перед ${label}=${value}`);
    }
  }

  const strength = sectionRows(text, 'Силовые подходы за одну тренировку');
  const indexOf = label => strength.findIndex(([l]) => l === label);
  assert.ok(
    indexOf('Разгибатели поясницы') < indexOf('Квадрицепсы'),
    '«Разгибатели поясницы» (3 подхода) должны стоять выше «Квадрицепсы» (2) при сортировке по убыванию',
  );
});

// ФИНАЛЬНОЕ РЕВЬЮ, пункт 8: item.muscles и item.load — два описания одного
// факта, и они уже расходились («Подкручивание таза лёжа» подписано «Таз и
// поясница», а размечено без поясницы). Отчёт печатал только колонки из load,
