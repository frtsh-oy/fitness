// Финальное ревью (М11): пояснительные абзацы раздела не держал ни один тест —
// удаление вводного абзаца и всей легенды «Откуда число» оставляло 416/416
// зелёными. Легенда — тот текст, без которого колонка basis («низ из
// источника, верх — наша линия») читателю непонятна, а её содержимое два
// других теста проверяют посимвольно. На экране каждая из пяти оговорок
// покрыта своим тестом — здесь была асимметрия между двумя потребителями
// одной сборки.
//
// Текст сверяется по «расплющенному» варианту (переносы строк — в пробелы):
// в файле абзац разложен по строкам ради ширины, и тест не должен падать от
// одной лишь переверстки.
function flat(text) {
  return text.replace(/\s+/g, ' ');
}

test('вводный абзац недельного раздела говорит, что и за какой срок посчитано', () => {
  const text = flat(buildReportLines().join('\n'));
  assert.match(text, /Сколько подходов получает каждая группа за неделю по всем тренировкам реестра/);
  assert.match(text, /Считается только силовая работа/);
});

test('легенда «Откуда число» объясняет все три основания и смешанный случай', () => {
  const text = flat(buildReportLines().join('\n'));
  assert.match(text, /Колонка «Откуда число» — как получена граница вердикта/);
  assert.match(text, /`определение`: на группу нет ни одного упражнения/);
  assert.match(text, /`источник`: граница подтверждена исследованием/);
  assert.match(text, /`наша линия`: общего числа в источниках нет, границу провели мы/);
  assert.match(text, /нижняя граница \(десять подходов\) из источника, а верхнюю \(двадцать\) провели мы/,
    'легенда не объясняет смешанную запись — а она стоит у «рабочего объёма», то есть у шести строк из двадцати');
});

// Финальное ревью (М10): у отчёта была своя дословная копия formatSets, и она
// не проверялась ничем — замена её тела на String(sets) оставляла 416/416
// зелёными, потому что на реальных данных все «наши» числа целые (18, 9, 6, 3,
// 0), а синтетическая фикстура выше даёт 22. Копия убрана (общая функция живёт
// в weekly-rows.js), но путь отчёта всё равно должен быть закрыт своим
// тестом: дробное «наше» число здесь бывает — вспомогательная доля 0.5 при
// нечётном числе кругов, — и в русском тексте оно пишется через запятую.
test('дробное «наше» число в отчёте печатается через запятую', () => {
  const text = buildReportLines({
    fixture: {
      title: 'Фикстура с половиной подхода',
      days: [1],
      blocks: [{
        nav: 'Блок', rounds: 1,
        items: [{ name: 'Синтетическое упражнение', muscles: 'Грудь', load: { chest: 0.5 }, kind: 'strength' }],
      }],
    },
  }).join('\n');
  assert.match(text, /\| Грудные \| 0 \| 0,5 \|/,
    'вспомогательная доля при одном круге должна дать «0,5» в колонке «Как на карте» и ноль в «Целевые»');
});
