// Единственный источник истины по инвентарю. Из него берут схема (допустимые
// значения gear), импорт таблицы (подписи в колонке «Инвентарь»), строка
// «Нужно» и шторка замены (подписи), и всё, что решает, подходит ли упражнение
// человеку. Новый вид инвентаря — одна строка в GEAR, и только после неё его
// можно писать в таблицу.

// Порядок — порядок на экране и в строке «Нужно»: одна и та же тренировка после
// замены упражнения не должна переставлять слова. Подписи строчные, как внутри
// фразы; с заглавной их пишет тот, кто ставит подпись отдельно (переключатель).
export const GEAR = Object.freeze([
  ['band_long', 'длинная резинка'],
  ['loop_short', 'мини-петля'],
  ['band_handles', 'резинка с ручками'],
  ['dumbbells', 'гантели'],
  ['kettlebell', 'гиря'],
].map(pair => Object.freeze(pair)));

// «Без инвентаря» стоит вне GEAR: человек его не «имеет» и не отмечает, оно
// доступно всегда. Поэтому его нет среди переключателей, но у упражнения оно
// законное значение gear.
export const NO_GEAR = 'none';
export const NO_GEAR_LABEL = 'без инвентаря';

// Все допустимые значения entry.gear.
export const GEAR_IDS = Object.freeze([...GEAR.map(([id]) => id), NO_GEAR]);

// Что отмечено, пока человек сам ничего не выбрал: приложение про тренировки с
// резинками, и у тех, кто им уже пользуется, ничего не должно меняться.
export const DEFAULT_OWNED = Object.freeze(['band_long', 'loop_short']);

// Map, а не обращение по объекту: «constructor» из ненадёжного источника
// (запись из localStorage, ячейка таблицы) не должен находиться как вид
// инвентаря.
const LABELS = new Map([...GEAR, [NO_GEAR, NO_GEAR_LABEL]]);

// Неизвестный id — повод упасть, а не вернуть undefined: на экран тогда попало
// бы «undefined» вместо подписи, и заметили бы это только на телефоне.
export function gearLabel(id) {
  if (!LABELS.has(id)) throw new Error(`Неизвестный инвентарь: ${id}`);
  return LABELS.get(id);
}

// Подписи списка видов через запятую, в порядке списка. Одним способом
// перечисляют инвентарь и карточка библиотеки, и шторка замены, и подсказки
// отказов («Есть с инвентарём: …»), и заголовки отчёта: второго способа,
// который разошёлся бы с первым в разделителе, нет.
export function gearNames(ids) {
  return ids.map(gearLabel).join(', ');
}

// Инвентарь упражнения, в порядке записи у упражнения.
export function gearText(entry) {
  return gearNames(entry.gear);
}

// Упражнение подходит, если каждый его вид инвентаря у человека есть: список
// gear — «нужно всё перечисленное», а не «что-нибудь одно». «Без инвентаря»
// подходит всегда, даже когда отмечено пусто.
export function fitsGear(entry, owned) {
  return entry.gear.every(id => id === NO_GEAR || owned.includes(id));
}

// Фильтрует библиотеку, не меняя порядок. Сохранённые тренировки и готовая
// тренировка через него не идут: человек их уже выбрал, и упражнение,
// пропавшее из них молча, — анти-цель конструктора.
export function fitLibrary(library, owned) {
  return library.filter(entry => fitsGear(entry, owned));
}

// Виды инвентаря, которые нужны этим упражнениям, а у человека не отмечены, в
// порядке словаря: «Есть с инвентарём: …» в отказе генератора и в шторке замены
// читается одинаково, в каком бы порядке ни шли упражнения. «Без инвентаря» сюда
// не попадает: оно доступно всегда.
export function unownedGear(entries, owned) {
  return GEAR.map(([id]) => id)
    .filter(id => !owned.includes(id) && entries.some(entry => entry.gear.includes(id)));
}
