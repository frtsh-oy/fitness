// Расчёт тренировочного объёма. Ни DOM, ни библиотеки карты, ни конкретной
// тренировки: на вход объект по схеме, на выход числа. Это же основание для
// будущей оценки недельной нагрузки, поэтому модуль обязан жить отдельно
// от рисования картинки.
import { MUSCLES, isMuscleId, toRegions } from './muscles.js';

// Сколько уровней объёма различает карта. Во время работы приложения эта
// константа ни на что не влияет: шкалу задаёт длина PALETTE из bodymap.js,
// которая уходит в библиотеку целиком, а PALETTE_STEPS приложение не
// импортирует — её читают только тесты. Это записанное здесь ожидание, за
// которым следят два теста: длина PALETTE обязана ей равняться («палитра ровно
// на число уровней объёма», test/bodymap.test.js), а силовой объём на регион —
// её не превышать («палитра закрывает максимальный силовой объём по всем
// тренировкам», test/volume.test.js). Смысл ожидания: объёмы выше шкалы
// библиотека красит последним оттенком, и различие между ними на карте
// пропадает. Силовой максимум на регион в нашей тренировке — ровно шесть
// подходов.
//
// Во втором режиме карты («вся нагрузка», MODE_KINDS в bodymap.js) объёмы выше
// шкалы есть уже сейчас: квадрицепсы 12.5, ягодичные 9.5, пресс 7 — все
// последним оттенком, вровень с верхом спины и его 5.5, который до шести
// округляется. Палитра откалибрована под силовой режим, потому что по
// программе растёт именно силовая нагрузка; «вся нагрузка» отвечает на другой
// вопрос — что тренировка задевает вообще. Решение осознанное (см. task-7-fix-1):
// относительная шкала под максимум режима сделала бы цвет несравнимым между
// режимами. Поэтому про верх шкалы прямо сказано в подписи под картой, а
// точное число подходов видно по клику.
export const PALETTE_STEPS = 6;

// Один проход по тренировке в её собственном порядке, с отбором по набору
// типов. Именно один проход, а не склейка результатов по типам: список
// упражнений из regionSummary показывается человеку и по клику прокручивает
// страницу к упражнению, поэтому его порядок обязан совпадать с порядком
// упражнений на странице. Склейка по типам дала бы сначала всю разминку, потом
// все силовые — на нашей тренировке случайно совпало бы с порядком блоков, а на
// тренировке с разминкой в середине уже нет.
function itemsOfKinds(workout, kinds) {
  const wanted = new Set(kinds);
  const rows = [];
  for (const block of workout.blocks) {
    for (const item of block.items) {
      if (!wanted.has(item.kind)) continue;
      rows.push({ item, rounds: block.rounds });
    }
  }
  return rows;
}

export function setsByGroup(workout, kind) {
  const sets = new Map();
  for (const { item, rounds } of itemsOfKinds(workout, [kind])) {
    for (const [group, share] of Object.entries(item.load)) {
      sets.set(group, (sets.get(group) ?? 0) + share * rounds);
    }
  }
  return sets;
}

export function setsByRegion(workout, kind) {
  const sets = new Map();
  for (const [group, value] of setsByGroup(workout, kind)) {
    if (!isMuscleId(group)) {
      throw new Error(`Неизвестная группа мышц: ${group}`);
    }
    const region = MUSCLES[group].region;
    sets.set(region, (sets.get(region) ?? 0) + value);
  }
  return sets;
}

// Всё, что карта показывает про один регион: точный объём и упражнения,
// которые его дают. На выходе Map региона на { sets, exercises }.
//
// kinds — массив типов, а не один тип: карта умеет показывать и одни силовые,
// и всю нагрузку сразу (см. MODE_KINDS в bodymap.js).
//
// sets — сумма «доля × круги» по тому же правилу, по которому считает
// docs/muscle-map.md (там по группам и раздельно по типам, здесь — по областям
// схемы и за типы режима), и без единого округления по дороге. Это не мелочь:
// карта и документ обязаны считать объём одинаково. Округляет только
// bodymap.js и только для выбора цвета — целая частота нужна библиотеке, а не
// человеку. Раньше округление шло по каждому упражнению, и сумма округлений
// расходилась с объёмом у половины регионов режима «вся нагрузка».
//
// exercises — в порядке тренировки, по одной записи на упражнение: toRegions
// сворачивает группы упражнения в регионы, поэтому две группы одного региона
// внутри одного упражнения («Тяга сидя»: широчайшие и верх спины) дают одно
// слагаемое в сумме и одну строку в списке, а не две.
export function regionSummary(workout, kinds) {
  const summary = new Map();
  for (const { item, rounds } of itemsOfKinds(workout, kinds)) {
    for (const [region, share] of toRegions(item.load)) {
      const row = summary.get(region) ?? { sets: 0, exercises: [] };
      row.sets += share * rounds;
      row.exercises.push(item.name);
      summary.set(region, row);
    }
  }
  return summary;
}
