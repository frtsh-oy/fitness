// Заглушка «Конструктора». Библиотеки упражнений и сборки своих тренировок
// сегодня нет — это дальше по дорожной карте, и экран не должен обещать
// обратное.
//
// hasSubscription передаётся параметром, а не читается модулем напрямую:
// экран отвечает за то, ЧТО сказать в каждом из двух случаев, а не за то,
// откуда берётся ответ на вопрос о подписке. Это же и делает обе ветки
// проверяемыми без подмены ../access.js — см. test/builder-view.test.js.
export function renderBuilder({ host, hasSubscription }) {
  const document = host.ownerDocument;
  host.textContent = '';
  const note = document.createElement('p');
  note.className = 'builder-note';
  note.textContent = hasSubscription()
    // Подписка есть, но строить пока нечего — это правда, и говорить о цене
    // здесь уже не о чем: раз подписка есть, платность не новость.
    ? 'Конструктор ещё не готов: библиотеки упражнений и сборки своих тренировок пока нет, хотя ваша подписка это уже разрешает — мы их просто ещё не построили.'
    // Подписки нет — рассказываем, что это за раздел и что в нём будет,
    // и сразу говорим, что он платный: без этого «нет доступа» выглядело бы
    // как временный сбой, а не как решение.
    : 'Конструктор — раздел для тех, кто хочет собирать тренировки сам: библиотека упражнений и свои комбинации вместо готовой программы. Раздел платный и пока не открыт: сначала здесь появится сама библиотека.';
  host.append(note);
}
