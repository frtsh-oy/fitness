// Группа упора получает не меньше FOCUS_MIN подходов в неделю: около десяти
// называет ACSM 2026 для роста мышц. SOFT_CEILING — верх полосы «рабочий
// объём» (load-bands.js): выше него генератор по возможности не поднимает ни
// одну основную группу, но условием это не делает.
export const FOCUS_MIN = 10;
export const SOFT_CEILING = 20;

// Силовых упражнений не больше 18, то есть девяти пар: это потолок пар в
// спеке, и генератор, не уложившись в него, отказывает, а не выдаёт лишнее.
// Зон упора не больше двух: каждая добавляет своё упражнение, и при пяти зонах
// тренировка разрастается до потолка, а упор теряет смысл.
export const MAX_STRENGTH = 18;
export const MAX_ZONES = 2;

// Нижние границы уровней и объём упора рассчитаны на три дня в неделю
