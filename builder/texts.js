// Неизвестный уровень или зона — повод упасть: по голому LEVELS[id] «constructor»
// нашёлся бы как уровень, и на экран попало бы «СВОЯ · UNDEFINED УРОВЕНЬ».
function levelOf(id) {
  if (!hasOwn(LEVELS, id)) throw new Error(`Неизвестный уровень: ${id}`);
  return LEVELS[id];
}

function zoneLabel(id) {
  if (!hasOwn(ZONES, id)) throw new Error(`Неизвестная зона: ${id}`);
  return ZONES[id].label.toLowerCase();
}

// Подсказка «как расти дальше» под тренировкой. level — идентификатор уровня или
// null у ручной сборки: у неё свои круги и запас повторов (MANUAL_*). Четвёртый
// пункт — только новичкам: у остальных уровней он был бы не про них. От формата
// силовой части зависит только начало первого пункта: что именно сохранять.
export function progressionFor(level, format = 'pairs') {
  const rounds = level === null ? MANUAL_ROUNDS : levelOf(level).rounds;
  const reserve = level === null ? MANUAL_RESERVE : levelOf(level).reserve;
  const keep = {
    pairs: `Сохраняй ${rounds} круга каждой силовой пары. `,
    loop: `Сохраняй ${rounds} ${plural(rounds, ['силовой круг', 'силовых круга', 'силовых кругов'])}. `,
    sets: `Сохраняй ${rounds} ${plural(rounds, ['подход', 'подхода', 'подходов'])} каждого упражнения. `,
  };
  if (!hasOwn(keep, format)) throw new Error(`Неизвестный формат: ${format}`);
  const items = [
    `${keep[format]}Заканчивай подход с запасом ${reserve} повторов до отказа.`,
    'Сделала на 1–2 повтора больше верхней границы в обоих подходах на двух тренировках подряд? Возьми резинку жёстче или перехвати её короче и вернись к нижней границе.',
    'Сохраняй амплитуду и контроль. Если приходится раскачиваться, более тугая резинка пока не подходит.',
  ];
  if (level === 'beginner') {
    items.push('Новичкам Американская коллегия спортивной медицины (ACSM) советует нагрузку примерно на 8–12 повторов. Если у упражнения дозировка больше, ориентируйся на неё и на запас повторов.');
  }
  return items;
}

export function kickerFor(level) {
  return level === null ? 'СВОЯ · СБОРКА ИЗ БИБЛИОТЕКИ' : `СВОЯ · ${levelOf(level).label.toUpperCase()} УРОВЕНЬ`;
}

// Упор называется только у подобранной по правилам: у ручной сборки правил
// уровня за спиной нет, и «упор» в её шапке был бы ничем не подкреплён.
export function leadFor(level, zones) {
  if (level === null) return 'Собрана из библиотеки упражнений.';
  const base = `Подобрана по правилам для уровня «${levelOf(level).label}».`;
  return zones.length > 0 ? `${base} Упор: ${zones.map(zoneLabel).join(', ')}.` : base;
}

// Подписи инвентаря в постоянном порядке словаря (gear.js), а не в порядке
// упражнений: одна и та же тренировка после замены упражнения не должна менять
// строку «Нужно». Коврик нужен всегда, «без инвентаря» (none) строку не
// удлиняет. Строка кончается точкой, как «Нужно: коврик, … стена.» у готовой
// тренировки: на одном экране они должны выглядеть одинаково.
export function equipmentFor(entries) {
  const used = new Set(entries.flatMap(e => e.gear));
  return `${['Нужно: коврик', ...GEAR.filter(([id]) => used.has(id)).map(([, name]) => name)].join(', ')}.`;
}

// «Всё тело» — тренировка всегда на всё тело, упор только добавка. Зоны — через
// «и» («ягодицы и спина»): названия идут в заголовок, где запятая читалась бы
// как перечисление трёх. Но если «и» уже есть в названии зоны («пресс и кор»),
// второй рядом сливается с ним в «пресс и кор и ягодицы»: тогда все через запятую.
export function defaultName(zones) {
  if (zones.length === 0) return 'Всё тело';
  const names = zones.map(zoneLabel);
  let list = names[0];
  if (names.length > 1) {
    list = names.some(name => name.includes(' и '))
      ? names.join(', ')
      : `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
  }
  return `Всё тело. Упор: ${list}`;
}
