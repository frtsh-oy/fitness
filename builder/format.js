// Вид силовой части своей тренировки и блоки, которые можно не брать. Только
// данные и одна функция чтения: модуль зовут и запись (builder/compact.js), и
// экран, поэтому своих зависимостей, кроме own.js, у него нет — иначе круг
// импортов замкнулся бы через compact.js.
//
// id «loop», а не «circuit»: circuit уже занят слотом разогрева, и в записи
// «circuit» значил бы две разные вещи.
import { hasOwn } from '../own.js';

// Подпись — на кнопке, пояснение — под переключателями. Отдых в «Круге» и в
// «Подходах» — инженерное суждение, а не заключение тренера, как и прочие
// числа отдыха в приложении.
export const FORMATS = {
  pairs: { label: 'Пары',    hint: 'Два упражнения по очереди, отдых после пары.' },
  loop:  { label: 'Круг',    hint: 'Все силовые подряд, отдых после круга.' },
  sets:  { label: 'Подходы', hint: 'Все подходы одного упражнения, потом следующее.' },
};

// Так собирали всегда, поэтому записи без поля format читаются именно так.
export const DEFAULT_FORMAT = 'pairs';

// Слоты, которые можно выключить целиком. Силовые не входят: без них нет
// тренировки. Выключенный слот — пустой список упражнений, отдельного поля нет.
export const OPTIONAL_SLOTS = ['warmup', 'circuit', 'cooldown'];

// Формат записи. Запись приходит из облака, и незнакомое значение (другая
// версия приложения, чужая правка) не повод её отбрасывать: читаем как «Пары».
// hasOwn, а не `in`: «toString» формата нет, хотя у объекта такое свойство есть.
export function formatOf(compact) {
  const { format } = compact;
  return typeof format === 'string' && hasOwn(FORMATS, format) ? format : DEFAULT_FORMAT;
}
