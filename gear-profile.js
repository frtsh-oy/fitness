// Что у человека есть дома: выбор видов инвентаря, по которому конструктор
// решает, какие упражнения ему предлагать (см. gear.js, fitsGear). Это настройка
// устройства, а не данные тренировки: лежит только в localStorage, в
// CloudStorage не идёт, и между устройствами выбор не переезжает (спека
// 2026-10-21-gear-profile-design.md, «Что меняется», п. 2).
import { GEAR, DEFAULT_OWNED } from './gear.js';

export const GEAR_KEY = 'gear-owned';

const ORDER = GEAR.map(([id]) => id);

// Оставляет известные виды без повторов и в порядке словаря: порядок не зависит
// от того, в какой очерёдности человек нажимал переключатели. «Без инвентаря»
// сюда не входит: его не «имеют», оно доступно всегда (gear.js, NO_GEAR). Чужой id
// из localStorage (запись другой версии, ручная правка) молча отбрасывается: на
// экране ему всё равно нет переключателя.
const normalize = ids => {
  const wanted = new Set(ids);
  return ORDER.filter(id => wanted.has(id));
};

// Сохранённое значение или значение по умолчанию. localStorage ненадёжен: он
// может бросить (приватный режим Safari, урезанный WebView), хранить не JSON или
// JSON не того вида. Любой такой исход — это «человек ещё ничего не выбирал», а
// не ошибка. Пустой массив — законный выбор «ничего нет», поэтому отличать его
// от отсутствия значения нужно по типу, а не по длине.
function read(local) {
  try {
    // Нет ключа или нет хранилища — undefined/null: JSON.parse их не принимает или
    // даёт не массив, и результат тот же, что у мусора.
    const parsed = JSON.parse(local?.getItem(GEAR_KEY));
    if (Array.isArray(parsed)) return normalize(parsed);
  } catch {
    // не JSON или хранилище бросило
  }
  return [...DEFAULT_OWNED];
}

// local — localStorage или null (нет вовсе). Читается один раз, при первом get():
// дальше правду о выборе говорит память, а localStorage — её копия на случай
// перезапуска. Поэтому, если запись не удалась, выбор всё равно живёт до закрытия
// приложения. По умолчанию в localStorage ничего не пишется: пока человек сам не
// выбрал, значение по умолчанию остаётся «по умолчанию», а не становится
// «выбранным» и не переживёт его смену в будущих версиях.
export function createGearProfile(local = null) {
  let owned = null;

  return {
    // Копия: вызывающий вправе менять массив, не трогая выбор.
    get() {
      owned ??= read(local);
      return [...owned];
    },

    set(ids) {
      // Строка вместо массива молча стала бы набором букв и пустым выбором:
      // дать выбору «ничего нет» по ошибке вызова хуже, чем упасть.
      if (!Array.isArray(ids)) throw new TypeError('Инвентарь передаётся массивом id');
      owned = normalize(ids);
      try {
        local?.setItem(GEAR_KEY, JSON.stringify(owned));
      } catch {
        // квота или приватный режим: выбор остаётся в памяти
      }
    },
  };
}
