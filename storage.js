// Прогресс живёт в CloudStorage внутри Telegram и в localStorage снаружи.
// Ключ включает дату, поэтому отметки сами сбрасываются на следующий день.
// Сами они при этом не исчезают, а CloudStorage держит не больше 1024 записей
// на человека, так что старые чистит prune() при запуске. Чистятся отметки
// СТАРШЕ вчерашних, вчерашние остаются: у другого устройства того же человека
// часовой пояс может быть другим, и наше «вчера» у него ещё сегодня.
import { createKv } from './kv.js';

// Ключ отметок — `m_<id тренировки>_<день>`, без двоеточий: CloudStorage
// принимает ключи только из A-Z a-z 0-9 _ - (1–128 символов), см.
// https://core.telegram.org/bots/webapps. Прежний ключ `w:<id>:<день>` под это
// правило не подходил, а значит, по документации, Telegram должен был
// отвечать на каждую запись отказом, который мы ловили и молча переживали:
// отметки, скорее всего, жили только на устройстве. На живом клиенте это не
// проверялось. Старые отметки не переносим — они живут один день, поэтому в
// день обновления сегодняшние начинаются заново, а остатки прежнего формата
// стирает prune().
export function storageKey(workoutId, date) {
  return `m_${workoutId}_${date}`;
}

// Сегодняшний день по МЕСТНОМУ времени — дословно как в src-original/app.js:47.
// 'en-CA' выбран не ради Канады, а ради формата: это единственная локаль, чья
// короткая дата и есть YYYY-MM-DD.
//
// Через toISOString() делать нельзя: она отдаёт день по UTC. Западнее Гринвича
// такой день переворачивается посреди вечера — при UTC-5 в 19:00 по местному
// времени наступает завтра, и отметки обнуляются прямо во время тренировки.
export function currentDay() {
  return new Date().toLocaleDateString('en-CA');
}

// Предыдущий день для YYYY-MM-DD. День здесь — строка, а не момент времени, и
// считается целиком по UTC: Date.UTC сам переходит через месяц, год и 29 февраля,
// а часовой пояс устройства в расчёте не участвует. Вычитание через местное
// время восточнее Гринвича дало бы позавчера: местная полночь там по UTC уже
// вчерашняя, и toISOString() отдала бы день на единицу меньше, чем надо.
export function yesterday(day) {
  const [year, month, date] = day.split('-').map(Number);
  return new Date(Date.UTC(year, month - 1, date - 1)).toISOString().slice(0, 10);
}

// Отметки на устройстве: прежний формат (`w:<id>:<день>`) тоже, чтобы его
// остатки не лежали вечно, и признак `:pending` рядом с любым из них.
const DEVICE_MARK = [
  /^m_.+_(\d{4}-\d{2}-\d{2})(:pending)?$/,
  /^w:.+:(\d{4}-\d{2}-\d{2})(:pending)?$/,
];
// В облаке бывает только новый формат и без признака: двоеточие туда не пускали.
const CLOUD_MARK = /^m_.+_(\d{4}-\d{2}-\d{2})$/;

// Ключ — отметка старше границы? Чужой ключ (раздел, своя тренировка) под
// шаблоны не подходит и потому никогда не считается устаревшим: трогать его
// чистка не вправе. Даты сравниваются как строки: у YYYY-MM-DD порядок
// строк и порядок дней совпадают.
function isStaleMark(key, patterns, cutoff) {
  for (const pattern of patterns) {
    const match = pattern.exec(key);
    if (match) return match[1] < cutoff;
  }
  return false;
}

// Признак «локальная копия не подтверждена облаком»: ставится вместе с самой
// записью и снимается, когда облако её подтвердило. Ключ производный от
// основного, поэтому он так же сбрасывается по дате вместе с отметками.
function pendingKey(key) {
  return `${key}:pending`;
}

function parseMarks(raw) {
  if (!raw) return new Set();
  try {
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? new Set(parsed) : new Set();
  } catch {
    return new Set();
  }
}

export function createStorage({ cloud = null, local = null, today = currentDay, cloudTimeout = 5000 } = {}) {
  // Сериализуем write-операции для каждого ключа (save и clear должны применяться в порядке вызова)
  const queues = new Map();

  // Доступ к обоим хранилищам, который не бросает и не реджектится, живёт в
  // kv.js: там же объяснено, почему обёрнуто всё и откуда три способа отказа облака.
  const { hasCloud, localGet, localSet, localRemove, localKeys, callCloud } = createKv({ cloud, local, cloudTimeout });

  const isPending = key => localGet(pendingKey(key)) === '1';
  const markPending = key => localSet(pendingKey(key), '1');
  const clearPending = key => localRemove(pendingKey(key));

  // Ставит задачу в очередь ключа: записи применяются в порядке вызова.
  // Обработчик один на оба исхода предыдущего звена намеренно: очередь не должна
  // вставать из-за чужого сбоя, а сами задачи ниже не реджектятся в принципе.
  const enqueue = (key, task) => {
    const chain = (queues.get(key) || Promise.resolve()).then(task, task);
    queues.set(key, chain);
    return chain;
  };

  const read = async key => {
    if (!hasCloud) return localGet(key);

    if (isPending(key)) {
      const raw = localGet(key);
      // Наша последняя запись не подтверждена облаком, значит облако заведомо
      // устарело — его ответ (в том числе успешный и пустой) не спрашиваем,
      // отдаём локальное значение. Именно это и не даёт отметке пропасть с экрана.
      // Обратная сторона правила: неподтверждённой считается и запись, чей ответ
      // не успел прийти до закрытия приложения, хотя облако её приняло. Тогда
      // локальная копия совпадает с облачной и решение ничего не меняет — кроме
      // случая, когда между этими двумя открытиями кто-то сбросил отметки с
      // другого устройства: его сброс мы увидим не сейчас, а после первой же
      // подтверждённой записи. Цена за то, чтобы не терять отмеченное.
      //
      // Досылать локальное значение в облако здесь НЕЛЬЗЯ: это был бы
      // last-write-wins заведомо несвежим источником. Пока это устройство было
      // офлайн, другое могло успешно записать в общее CloudStorage более полный
      // набор — досылка молча откатила бы его, причём без единого действия
      // пользователя, просто по факту открытия тренировки. Досылка не нужна:
      // приложение сохраняет весь текущий набор целиком, а не разницу, поэтому
      // первое же успешное save после восстановления связи донесёт отметки
      // штатным путём и с актуальным набором на руках.
      //
      // Признак без локального значения (localStorage не отдал его или отказал
      // на записи самой отметки, приняв только короткий признак) защищать нечего:
      // читаем облако обычным порядком.
      if (raw) return raw;
    }

    const { ok, value } = await callCloud('getItem', [key]);
    // Решает НЕ наличие локальной копии, а признак: копия теперь есть всегда
    // (localStorage — сквозной кэш, см. write), и отдавать её вместо успешного
    // ответа облака значило бы воскрешать отметки, сброшенные с другого
    // устройства. Неподтверждённых записей нет → успешному ответу верим как
    // есть, даже пустому. Отказ любым из трёх способов → читаем localStorage:
    // ровно за этим кэш и нужен.
    return ok ? value : localGet(key);
  };

  const write = (key, value) => {
    // localStorage — сквозной кэш, а не запасной выход: пишем в него ВСЕГДА и
    // синхронно, до обращения к облаку. Пока запись шла только в ветку отказа,
    // при работающем облаке локальная копия оставалась пустой — и одного
    // открытия без сети хватало, чтобы увидеть ноль отметок вместо двадцати,
    // отметить пару и следующей же удачной записью затереть в облаке день.
    // Синхронно — потому что flushSave зовут на выгрузке страницы: всё, что
    // отложено хотя бы на микрозадачу, там умирает вместе с вкладкой.
    localSet(key, value);
    if (!hasCloud) return Promise.resolve();

    // Признак ставится вместе с записью, а не по факту отказа: «неподтверждённая»
    // — это в том числе запись, ответа на которую мы не дождались, потому что
    // приложение закрыли. Для следующего чтения она ничем не отличается от
    // отказавшей, и защищать её надо так же.
    markPending(key);

    return enqueue(key, async () => {
      if (!(await callCloud('setItem', [key, value])).ok) return;
      // Признак снимаем, только если в localStorage всё ещё ровно то значение,
      // которое подтвердило облако. Пока эта запись ждала своей очереди, человек
      // мог отметить ещё круг: его набор уже лежит локально, а в облако только
      // поедет. Снять признак здесь значило бы объявить подтверждённым то, чего
      // облако не видело.
      if (localGet(key) === value) clearPending(key);
    });
  };

  const drop = key => {
    // Сброс виден локально сразу и синхронно, как и запись: устаревшая копия не
    // должна пережить его ни при отказе облака, ни при выгрузке страницы.
    // Признак снимается и без облака: там он не ставится и не читается, но
    // после сброса локальных следов не должно оставаться при любом бэкенде.
    localRemove(key);
    clearPending(key);
    if (!hasCloud) return Promise.resolve();

    // Исход облака здесь ни на что не влияет и потому не проверяется:
    // локальная часть уже сделана, повторять её по ответу нечем и незачем.
    return enqueue(key, () => callCloud('removeItem', [key]));
  };

  return {
    async load(workoutId) {
      return parseMarks(await read(storageKey(workoutId, today())));
    },
    async save(workoutId, marks) {
      await write(storageKey(workoutId, today()), JSON.stringify([...marks]));
    },
    async clear(workoutId) {
      await drop(storageKey(workoutId, today()));
    },
    // Стирает отметки старше вчерашнего дня. Не бросает и не реджектится:
    // приложение зовёт её при запуске и идёт дальше, а любой сбой чистки значит
    // лишь «в другой раз». Устройство чистится синхронно, до первого обращения
    // к облаку: облако отвечает долго или молчит, а мусор рядом ждать не должен.
    prune() {
      // Единственное, что здесь может бросить, — день: today() подменяют
      // снаружи, и из неразборчивой строки Date.UTC делает Invalid Date, а
      // toISOString() на нём бросает RangeError. Без границы стирать нечего —
      // ни на устройстве, ни в облаке, — и запуск из-за этого падать не должен.
      let cutoff;
      try {
        cutoff = yesterday(today());
      } catch {
        return Promise.resolve();
      }

      for (const key of localKeys()) {
        if (isStaleMark(key, DEVICE_MARK, cutoff)) localRemove(key);
      }
      if (!hasCloud) return Promise.resolve();

      return (async () => {
        const { value } = await callCloud('getKeys', []);
        // Списка нет — стирать нечего. Отдельной проверки на отказ тут нет:
        // при отказе callCloud сам отдаёт value '', а не обрезанный или чужой
        // ответ, и '' (как и null от удачного вызова) списком не является.
        if (!Array.isArray(value)) return;
        const staleKeys = value.filter(key => isStaleMark(key, [CLOUD_MARK], cutoff));
        // Исход removeItems ничего не меняет: устаревшее подберёт следующий запуск
        if (staleKeys.length) await callCloud('removeItems', [staleKeys]);
      })();
    },
  };
}
