// Генерирует docs/muscle-map.md — сводку разметки мышц (поле load в
// workouts/*.js) для вычитки человеком. Разметка составлена по описаниям
// упражнений, это инженерное суждение, а не заключение тренера: ошибка в ней
// ничего не ломает и нигде не падает, а тихо искажает будущую оценку нагрузки.
// Отсюда и требование к этому файлу: то, что он печатает, должно быть
// дословно верно — вычитывающий человек не увидит исходных данных, только текст.
//
// Запуск: node tools/muscle-report.js
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MUSCLES, muscleLabel } from '../muscles.js';
import { WORKOUTS } from '../workouts/index.js';
import { weeklyRows } from '../weekly-rows.js';

const KIND_LABELS = { warmup: 'Разминка', strength: 'Силовое', cooldown: 'Заминка' };

// Как muscleLabel в muscles.js: неизвестное значение — это повод упасть, а не
// молча протащить английский идентификатор в русский текст отчёта. Тихий
// фолбэк на item.kind был бы решением, которое ничего не решает: на
// провалидированных данных он недостижим, а если всё-таки сработает —
// испортит документ незаметно для читателя.
function kindLabel(kind) {
  const label = KIND_LABELS[kind];
  if (!label) throw new Error(`Неизвестный kind: ${kind}`);
  return label;
}

// Порядок и заголовки сводных таблиц подходов. Силовая идёт первой: именно на
// ней построена прогрессия программы (progression в workouts/*.js говорит
// только про силовые пары). Разминка и заминка — с примечанием, почему их
// нельзя складывать с силовой в одно число: резинка там лёгкая, без роста
// нагрузки, и это качественно другое усилие, а не тот же «подход».
const KIND_SECTIONS = [
  { kind: 'strength', heading: 'Силовые подходы за одну тренировку', note: null },
  {
    kind: 'warmup', heading: 'Дополнительно нагружаются в разминке',
    note: 'Разминочные раунды идут с лёгкой резинкой и не растут по программе — это не силовой подход.',
  },
  {
    kind: 'cooldown', heading: 'Дополнительно нагружаются в заминке',
    note: 'Заминка — это удержание на растяжку, а не подход на повторения.',
  },
];

function muscleColumns(load) {
  const primary = Object.entries(load).filter(([, v]) => v === 1).map(([id]) => muscleLabel(id));
  const secondary = Object.entries(load).filter(([, v]) => v === 0.5).map(([id]) => muscleLabel(id));
  return [primary.join(', ') || '—', secondary.join(', ') || '—'];
}

function reportForWorkout(workout) {
  // Колонка «Подпись в приложении» — это item.muscles, тот самый текст, который
  // человек видит на карточке упражнения. Он и размеченные группы описывают
  // одно и то же разными словами, то есть могут разойтись — и раньше отчёт это
  // расхождение прятал, печатая только колонки из load.
  const lines = [`## ${workout.title}`, '',
    '| Блок | Упражнение | Подпись в приложении | Целевые | Вспомогательные | Тип |', '|---|---|---|---|---|---|'];

  // Подходы по группам мышц, раздельно по типу упражнения:
  // totalsByKind.get(kind) → Map(id группы -> сумма value * rounds блока).
  // Раздельно намеренно — см. комментарий у KIND_SECTIONS.
  const totalsByKind = new Map();
  for (const block of workout.blocks) {
    for (const item of block.items) {
      const [primary, secondary] = muscleColumns(item.load);
      lines.push(`| ${block.nav} | ${item.name} | ${item.muscles} | ${primary} | ${secondary} | ${kindLabel(item.kind)} |`);

      const kindTotals = totalsByKind.get(item.kind) ?? new Map();
      for (const [id, value] of Object.entries(item.load)) {
        kindTotals.set(id, (kindTotals.get(id) ?? 0) + value * block.rounds);
      }
      totalsByKind.set(item.kind, kindTotals);
    }
  }

  for (const { kind, heading, note } of KIND_SECTIONS) {
    const totals = totalsByKind.get(kind);
    if (!totals || totals.size === 0) continue; // нечего показывать — не рисуем пустую таблицу
    lines.push('', `### ${heading}`, '');
    if (note) lines.push(note, '');
    lines.push('| Группа | Подходов |', '|---|---|');
    for (const [id, sum] of [...totals].sort((a, b) => b[1] - a[1])) {
      lines.push(`| ${muscleLabel(id)} | ${sum} |`);
    }
  }

  // Эта строка обязана учитывать упражнения ЛЮБОГО типа, а не только силовые.
  // Раньше она считалась от одних силовых totals и поэтому могла назвать
  // незадействованной группу, которая на деле грузится в разминке несколько
  // кругов за тренировку, — то есть прямо соврать читателю, который как раз и
  // вычитывает эту разметку. Здесь — объединение всех totalsByKind, поэтому в
  // списке остаются только группы, которых нет ни в одном load.
  //
  // Говорит она именно про разметку, а не про тело. «Не задействованы ни в
  // одном упражнении» было сильнее того, что тут посчитано, и на предплечьях
  // оказалось прямой неправдой: резинку держат руками в шести упражнениях.
  // Разметка нагрузку от хвата не учитывает — она с лёгкой резинкой не
  // поднимается над фоном, — и отсутствие группы в load означает ровно это.
  const touchedAnywhere = new Set();
  for (const totals of totalsByKind.values()) {
    for (const id of totals.keys()) touchedAnywhere.add(id);
  }
  const untouched = Object.keys(MUSCLES).filter(id => !touchedAnywhere.has(id)).map(muscleLabel);
  lines.push('', `Нет разметки ни в одном упражнении: ${untouched.join(', ') || '—'}`, '');

  return lines;
}

// Недельный объём: то же самое, что показывает экран калькулятора — сборка
// строк общая (weekly-rows.js: расчёт weekly.js + вердикт load-bands.js +
// подпись muscles.js, уже отсортированные), поэтому экран и отчёт разойтись
// не могут. Раздел ставится в начале отчёта, чтобы перекос было видно сразу
// при добавлении упражнений, а не только с телефона.
function weeklyLines(workouts) {
  const rows = weeklyRows(Object.values(workouts));

  const lines = [
    '## Недельный объём', '',
    'Сколько подходов получает каждая группа за неделю по всем тренировкам',
    'реестра, с учётом того, сколько дней в неделю идёт каждая тренировка.',
    'Считается только силовая работа.', '',
    'Два числа, потому что счёт разный. «Целевые» — только те упражнения, где',
    'группа целевая, и односторонние считаются по сторонам: в этой системе',
    'получены ориентиры, поэтому по ней и вердикт. «Как на карте» —',
    'вспомогательная работа идёт половиной, односторонние один раз.', '',
    'Счёт односторонних по сторонам — наше чтение, а не цитата: договорённости',
    'об этом в проверенных источниках нет.', '',
    'Колонка «Откуда число» — как получена граница вердикта. `определение`:',
    'на группу нет ни одного упражнения. `источник`: граница подтверждена',
    'исследованием. `наша линия`: общего числа в источниках нет, границу',
    'провели мы. Смешанная запись у «рабочего объёма» — нижняя граница (десять',
    'подходов) из источника, а верхнюю (двадцать) провели мы. Обоснование',
    'каждой полосы и ссылки на источники — в `load-bands.js`.', '',
    '| Группа | Целевые | Как на карте | Вердикт | Откуда число |',
    '|---|---|---|---|---|',
  ];
  for (const row of rows) {
    lines.push(`| ${row.label} | ${fmt(row.comparable)} | ${fmt(row.ours)} | ${row.band.verdict} | ${row.band.basis} |`);
  }
  lines.push('');
  return lines;
}

// Как formatSets в weekly-view.js: дробным бывает только «наше» число
// (вспомогательная доля на нечётном числе кругов), сопоставимое — всегда
// целое. Разделитель дробной части — запятая, как в остальном тексте отчёта.
function fmt(sets) {
  return String(sets).replace('.', ',');
}

