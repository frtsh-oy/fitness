    'ничего и в суммы подходов ниже не входят.', '',
    'Подходы ниже посчитаны раздельно для силовых, разминочных и заминочных',
    'упражнений — это разная по характеру нагрузка, и складывать её в одно число',
    'означало бы уравнять лёгкую разминку с рабочим силовым подходом. Число в',
    'таблице — это вклад упражнения (1 для целевой группы, 0.5 для вспомогательной),',
    'умноженный на число кругов блока и просуммированный по упражнениям; отсюда',
    'дробные значения вроде 1.5. Строка «Нет разметки» — про упражнения всех',
    'типов сразу: в ней те группы, которых нет ни в одном load. Это',
    'утверждение про разметку, а не про тело: группа из этого списка всё',
    'равно может участвовать в движении — просто не настолько, чтобы это',
    'стоило отдельной доли нагрузки.', '',
    'Хват резинки — ровно такой случай: доля предплечьям ставится по',
    'правилу, а не на глаз. Длинная резинка (`band_long`) не имеет отдельных',
    'креплений и держится только руками, поэтому хват есть у неё всегда —',
    'такому упражнению предплечья ставятся вспомогательной долей 0.5.',
    'Короткая петля (`loop_short`) даёт хват, только когда её держат руками,',
