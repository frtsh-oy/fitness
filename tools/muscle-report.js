    'Разметку делал разработчик, а не тренер: он читал текстовые описания',
    'упражнений и сам решал, какая мышца где работает. Специалист по тренировкам',
    'её не проверял. Ошибка здесь ничего не сломает и никак не проявит себя в',
    'приложении — увидеть её может только человек, читающий эту таблицу.', '',
    'Если что-то здесь выглядит не так — кажется, что упражнение нагружает не те',
    'мышцы, или важная нагрузка вообще пропущена, — ничего исправлять самому не',
    'нужно. Достаточно своими словами описать, какое упражнение вызывает сомнение',
    'и что именно не так; правку в данные внесёт разработчик.', '',
    'Колонка «Подпись в приложении» — это тот текст, который видно на карточке',
    'упражнения в самом приложении. Он и размеченные группы рядом описывают одно',
    'и то же, только разными словами, и поэтому могут разойтись: если подпись',
    'говорит про поясницу, а среди групп её нет, — это как раз то, что стоит',
    'заметить.', '',
    'Тире в колонке означает, что таких групп у упражнения нет: в «Целевые» —',
    'что все размеченные группы вспомогательные, в «Вспомогательные» — что все',
    'целевые, а сразу в обеих — что разметки нагрузки у упражнения нет вовсе.',
